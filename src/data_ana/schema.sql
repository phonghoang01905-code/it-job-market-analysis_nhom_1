CREATE TABLE IF NOT EXISTS companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    name_key TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    source_job_id TEXT,
    url TEXT,
    title TEXT NOT NULL,
    company_id BIGINT REFERENCES companies(id),
    location TEXT NOT NULL DEFAULT '',
    city TEXT NOT NULL DEFAULT '',
    level TEXT NOT NULL DEFAULT 'Unknown',
    work_model TEXT NOT NULL DEFAULT 'Unknown',
    description TEXT NOT NULL DEFAULT '',
    salary_text TEXT NOT NULL DEFAULT '',
    salary_currency TEXT,
    salary_period TEXT,
    salary_min_original NUMERIC(18, 2),
    salary_max_original NUMERIC(18, 2),
    salary_min NUMERIC(18, 2),
    salary_max NUMERIC(18, 2),
    usd_vnd_rate NUMERIC(12, 4) NOT NULL CHECK (usd_vnd_rate > 0),
    posted_date DATE,
    posted_date_text TEXT NOT NULL DEFAULT '',
    scraped_at TIMESTAMPTZ NOT NULL,
    inserted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT jobs_source_id_unique UNIQUE(source, source_job_id),
    CONSTRAINT jobs_source_url_unique UNIQUE(source, url),
    CONSTRAINT jobs_identity_required CHECK (source_job_id IS NOT NULL OR url IS NOT NULL),
    CONSTRAINT jobs_salary_positive CHECK ((salary_min IS NULL OR salary_min >= 0) AND (salary_max IS NULL OR salary_max >= 0)),
    CONSTRAINT jobs_salary_order CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_min <= salary_max)
);

CREATE TABLE IF NOT EXISTS job_skills (
    job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES skills(id),
    PRIMARY KEY(job_id, skill_id)
);

CREATE INDEX IF NOT EXISTS jobs_company_idx ON jobs(company_id);
CREATE INDEX IF NOT EXISTS jobs_scraped_at_idx ON jobs(scraped_at);
CREATE INDEX IF NOT EXISTS job_skills_skill_idx ON job_skills(skill_id);
